def _item_rows(items):
    cells = []
    for item in items:
        group = GROUP_NAMES.get(item.get("group"), f"第 {item.get('group')} 组")
        cells.append(
            '<tr><td class="grp">{}</td><td class="name">{}</td>'
            '<td class="why">{}</td></tr>'.format(
                html.escape(str(group)),
                html.escape(str(item.get("subject", ""))),
                html.escape(str(item.get("detail", ""))),
            )
        )
    return "<table><tr><th>检查项</th><th>对象</th><th>原因</th></tr>{}</table>".format(
        "".join(cells)
    )


def write_failure_page(report, path, elapsed=0.0, json_path=""):
    """把失败项渲染成一个离线 HTML 警告页（无外部依赖，mshta/IE 也能正常显示）。"""
    statuses = report.statuses()
    failures = report.failures()
    warnings = report.warnings()

    fail_rows = _item_rows(failures) if failures else "<p>（没有失败项）</p>"
    if warnings:
        warn_block = '<h2 class="w">警告（{0} 项，不阻断打包）</h2>{1}'.format(
            len(warnings), _item_rows(warnings)
        )
    else:
        warn_block = ""

    page = (
        PAGE_TEMPLATE.replace("__TIME__", time.strftime("%Y-%m-%d %H:%M:%S"))
        .replace("__ELAPSED__", f"{elapsed:.1f}")
        .replace("__OK__", str(statuses[OK]))
        .replace("__WARN__", str(statuses[WARN]))
        .replace("__FAIL__", str(statuses[FAIL]))
        .replace("__FAIL_ROWS__", fail_rows)
        .replace("__WARN_BLOCK__", warn_block)
        .replace("__PROJECT__", html.escape(str(PROJECT)))
        .replace("__JSON__", html.escape(str(json_path)))
    )
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(page, encoding="utf-8", newline="\r\n")
    return path


def wait_before_packaging(seconds=5):
    if seconds <= 0:
        return
    for remaining in range(seconds, 0, -1):
        print(f"\r{remaining} 秒后开始打包主程序...", end="", flush=True)
        time.sleep(1)
    print("\r构建前检查通过，开始打包主程序。      ")


