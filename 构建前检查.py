def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")

    parser = argparse.ArgumentParser(description="构建前完整性检查")
    parser.add_argument("--no-wait", action="store_true", help="检查结束后不等待 5 秒")
    parser.add_argument(
        "--wait", type=int, default=5, help="通过后等待的秒数（默认 5）"
    )
    parser.add_argument(
        "--run",
        action="store_true",
        help="真实启动 PyInstaller 工具做冒烟探测（这些工具会改系统配置，默认不执行）",
    )
    parser.add_argument(
        "--jobs", type=int, default=0, help="并发线程数（默认按 CPU 自动）"
    )
    parser.add_argument(
        "--json",
        default=str(VALIDATION_DIR / "prebuild-check.json"),
        help="JSON 报告输出路径",
    )
    parser.add_argument(
        "--page",
        default=str(VALIDATION_DIR / "prebuild-fail.html"),
        help="失败时输出的警告页面路径（通过时会被删除）",
    )
    args = parser.parse_args(argv)

    jobs = args.jobs if args.jobs > 0 else min(8, (os.cpu_count() or 4))
    started = time.perf_counter()
    report = Report()

    print("=" * 78)
    print(f"构建前完整性检查  {time.strftime('%Y-%m-%d %H:%M:%S')}")
    print(f"工程目录：{PROJECT}")
    print(f"并发线程：{jobs}" + ("   真实启动探测：开启" if args.run else ""))
    print("=" * 78)
    sys.stdout.flush()

    # 1. 7z 压缩包
    archives = sorted(FILES_DIR.glob("*.7z"))

    def archive_worker(path):
        try:
            verify_archive(path)
        except Invalid as exc:
            return FAIL, str(exc)
        return OK, f"{path.stat().st_size / 1048576:.1f} MB"

    run_stage(
        report,
        1,
        4,
        "7z 压缩包 CRC 校验",
        jobs,
        archives,
        archive_worker,
        label=lambda path: f"files/{path.name}",
    )

    # 2. exe / dll
    binaries = sorted(list(FILES_DIR.glob("*.exe")) + list(FILES_DIR.glob("*.dll")))

    def binary_worker(path):
        try:
            machine, sections = inspect_pe(path)
        except Invalid as exc:
            return FAIL, str(exc)
        kind = "x64" if machine == 0x8664 else "x86"
        return OK, f"{kind} / {sections} 节 / {path.stat().st_size / 1048576:.1f} MB"

    run_stage(
        report,
        2,
        4,
        "exe/dll 二进制有效性",
        jobs,
        binaries,
        binary_worker,
        label=lambda path: f"files/{path.name}",
    )

    # 3. makefile.py 载荷
    if not RESOURCE_DIR.is_dir():
        print(
            f"[3/4] 内嵌载荷一致性 {'-' * 20} 目录不存在：先执行 "
            f"Python\\Python.exe makefile.py 生成 {RESOURCE_DIR.name}\\"
        )
    try:
        entries = load_payload_entries()
    except Invalid as exc:
        report.add(3, "makefile.py", FAIL, str(exc))
        print(f"[3/4] 内嵌载荷一致性 {'-' * 20} 无法读取 makefile.py：{exc}")
        entries = []

    def payload_worker(entry):
        source_name, module_name, var_name = entry
        problems = check_payload(source_name, module_name, var_name)
        if problems:
            return FAIL, "；".join(problems)
        return OK, module_name

    run_stage(
        report,
        3,
        4,
        "内嵌载荷一致性",
        jobs,
        entries,
        payload_worker,
        label=lambda entry: entry[0],
    )

    for orphan in find_orphan_payloads(entries):
        report.add(3, orphan, WARN, "载荷存在但 makefile.py 未登记（会被打包规则忽略）")

    # 4. PyInstaller 工具
    try:
        targets = load_tool_targets()
    except Invalid as exc:
        report.add(4, "make_pythontools_files.bat", FAIL, str(exc))
        print(f"[4/4] PyInstaller 工具 \t 无法读取：{exc}")
        targets = []

    def tool_worker(target):
        name, script = target
        failures, warnings = check_tool(name, script)
        if failures:
            return FAIL, "；".join(failures)
        if warnings:
            return WARN, "；".join(warnings)
        return OK, script

    run_stage(
        report,
        4,
        4,
        "PyInstaller 工具归档与导入闭包",
        jobs,
        targets,
        tool_worker,
        label=lambda target: f"{target[0]}.exe",
    )

    if args.run and targets:

        def probe_worker(target):
            return probe_tool(target[0])

        run_stage(
            report,
            4,
            4,
            "PyInstaller 工具启动探测",
            min(4, jobs),
            targets,
            probe_worker,
            label=lambda target: f"{target[0]}.exe",
        )

    # 汇总
    elapsed = time.perf_counter() - started
    statuses = report.statuses()
    print("-" * 78)
    print(
        f"结果：通过 {statuses[OK]}  警告 {statuses[WARN]}  失败 {statuses[FAIL]}"
        f"   总用时 {elapsed:.1f}s"
    )
    render_details(report)

    try:
        VALIDATION_DIR.mkdir(parents=True, exist_ok=True)
        Path(args.json).parent.mkdir(parents=True, exist_ok=True)
        Path(args.json).write_text(
            json.dumps(
                {
                    "time": time.strftime("%Y-%m-%d %H:%M:%S"),
                    "project": str(PROJECT),
                    "run_probe": bool(args.run),
                    "elapsed": round(elapsed, 2),
                    "statuses": statuses,
                    "stages": [list(stage) for stage in report.stages],
                    "items": report.items,
                },
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )
        print(f"报告已写入：{args.json}")
    except OSError as exc:
        print(f"报告写入失败（不影响结论）：{exc}")

    if statuses[FAIL]:
        try:
            page = write_failure_page(report, args.page, elapsed, args.json)
            print(f"警告页面已写入：{page}")
        except OSError as exc:
            print(f"警告页面写入失败（不影响结论）：{exc}")
        print("=" * 78)
        print("构建前检查未通过，已中止打包。")
        return 1

    # 通过时清掉上次残留的失败页面，避免打包脚本误弹旧页面
    try:
        Path(args.page).unlink()
    except OSError:
        pass

    print("=" * 78)
    if not args.no_wait:
        wait_before_packaging(args.wait)
    return 0


if __name__ == "__main__":
    sys.exit(main())
