def load_tool_targets():
    """从 make_pythontools_files.bat 里取出 (exe 名, 入口脚本) 列表。"""
    if not TOOLS_BATCH.is_file():
        raise Invalid("缺少 make_pythontools_files.bat")
    text = TOOLS_BATCH.read_bytes().decode("gbk", "replace")
    targets = []
    for line in text.splitlines():
        if "PyInstaller" not in line or "-n " not in line:
            continue
        name_match = re.search(r"-n\s+([\w.\-]+)", line)
        script_match = re.search(r"([\w.\-]+\.py)\s*$", line.strip())
        if name_match and script_match:
            targets.append((name_match.group(1), script_match.group(1)))
    if not targets:
        raise Invalid("make_pythontools_files.bat 里没有解析到 PyInstaller 目标")
    return targets


def collect_imports(tree):
    """收集顶层模块名，并标记该导入是否全部发生在 try 块里。"""
    found = {}

    def visit(node, guarded):
        if isinstance(node, ast.Try):
            for child in node.body:
                visit(child, True)
            for child in list(node.orelse) + list(node.handlers) + list(node.finalbody):
                visit(child, guarded)
            return
        try_star = getattr(ast, "TryStar", None)
        if try_star is not None and isinstance(node, try_star):
            for child in node.body:
                visit(child, True)
            for child in list(node.orelse) + list(node.handlers) + list(node.finalbody):
                visit(child, guarded)
            return
        if isinstance(node, ast.Import):
            for alias in node.names:
                top = alias.name.split(".")[0]
                found[top] = found.get(top, True) and guarded
            return
        if isinstance(node, ast.ImportFrom):
            if node.level or not node.module:
                return
            top = node.module.split(".")[0]
            found[top] = found.get(top, True) and guarded
            return
        for child in ast.iter_child_nodes(node):
            visit(child, guarded)

    visit(tree, False)
    return found


def build_closure(entry_script):
    """返回 (已分析的本地模块, {顶层模块名: 是否只出现在 try 里})。"""
    local_modules = {}
    for path in PROJECT.glob("*.py"):
        local_modules.setdefault(path.stem, path)

    analysed = {}
    imports = {}
    pending = [entry_script]
    while pending:
        current = pending.pop()
        if current in analysed:
            continue
        try:
            source = current.read_text(encoding="utf-8", errors="replace")
            tree = ast.parse(source)
        except (OSError, SyntaxError) as exc:
            raise Invalid(f"{current.name} 无法解析：{exc}")
        analysed[current] = source
        for name, guarded in collect_imports(tree).items():
            imports[name] = imports.get(name, True) and guarded
            target = local_modules.get(name)
            if target is not None:
                pending.append(target)
    return analysed, imports


def _archive_entries(archive):
    toc = archive.toc
    return toc if isinstance(toc, dict) else dict(toc)


def _read_archive_entry(archive, entries, name):
    """读出 CArchive 里一个数据条目的原始内容（必要时解压）。"""
    offset, length, _, compressed, _ = entries[name]
    with open(archive._filename, "rb") as handle:
        handle.seek(archive._start_offset + offset)
        data = handle.read(length)
    if compressed:
        data = zlib.decompress(data)
    return data


def _normalize_zip_member(name):
    if name.endswith(".pyc"):
        name = name[: -len(".pyc")]
    name = name.replace("\\", "/").replace("/", ".")
    if name.endswith(".__init__"):
        name = name[: -len(".__init__")]
    return name


def bundled_modules(archive, entries):
    """把包内所有"能被 import 到"的顶层模块名汇总起来。

    PyInstaller 6 的模块分布在四处：PYZ 归档、CArchive 里的 'm'（冻结模块，
    如 struct）、扩展模块 .pyd（如 win32\\win32api.pyd）、以及 bootstrap 用的
    base_library.zip（os / re / collections 这类基础库，成员名形如 re/__init__.pyc）。
    """
    available = set(sys.builtin_module_names) | set(IGNORED_MODULES)
    for name, info in entries.items():
        kind = info[-1]
        if kind in ("m", "s"):
            available.add(name)
            continue
        if kind not in ("b", "x"):
            continue
        clean = name.replace("\\", "/")
        base = clean.rsplit("/", 1)[-1]
        lowered = base.lower()
        if lowered.endswith((".pyd", ".dll", ".so")):
            available.add(base.rsplit(".", 1)[0])
            parts = clean.split("/")
            if len(parts) > 1:
                available.add(parts[-2])

    if "base_library.zip" in entries:
        try:
            with zipfile.ZipFile(
                io.BytesIO(_read_archive_entry(archive, entries, "base_library.zip"))
            ) as inner:
                for member in inner.namelist():
                    normalized = _normalize_zip_member(member)
                    available.add(normalized)
                    parts = normalized.split(".")
                    for index in range(1, len(parts)):
                        available.add(".".join(parts[:index]))
        except (OSError, KeyError, zipfile.BadZipFile, zlib.error):
            pass
    return available


def check_tool(name, script):
    """返回 (失败列表, 警告列表)。"""
    from PyInstaller.archive.readers import CArchiveReader

    failures = []
    warnings = []
    executable = FILES_DIR / f"{name}.exe"
    if not executable.is_file():
        return [f"缺少 files/{name}.exe"], warnings

    try:
        inspect_pe(executable)
    except Invalid as exc:
        return [f"PE 结构不合法：{exc}"], warnings

    try:
        archive = CArchiveReader(str(executable))
        entries = _archive_entries(archive)
    except Exception as exc:
        return [f"PyInstaller 归档无法解析：{type(exc).__name__}: {exc}"], warnings

    pyz_names = [entry for entry, info in entries.items() if info[-1] == "z"]
    if len(pyz_names) != 1:
        failures.append(f"归档里的 PYZ 数量异常（{len(pyz_names)}）")
        return failures, warnings
    try:
        pyz = archive.open_embedded_archive(pyz_names[0])
        bundled = set(_archive_entries(pyz))
    except Exception as exc:
        return [f"PYZ 无法解析：{type(exc).__name__}: {exc}"], warnings
    if not bundled:
        failures.append("PYZ 里没有任何模块")
    bundled |= bundled_modules(archive, entries)

    entry_stem = Path(script).stem
    script_types = {entry for entry, info in entries.items() if info[-1] == "s"}
    if entry_stem not in script_types:
        failures.append(f"归档里找不到入口脚本 {entry_stem}")

    packed = {entry.replace("\\", "/") for entry in entries}
    source_path = PROJECT / script
    if not source_path.is_file():
        failures.append(f"缺少入口源码 {script}")
        return failures, warnings

    try:
        analysed, imports = build_closure(source_path)
    except Invalid as exc:
        failures.append(str(exc))
        return failures, warnings

    for module in sorted(imports):
        if module in IGNORED_MODULES or module in bundled or module in script_types:
            continue
        if imports[module]:
            warnings.append(f"可选模块未随包（源码里在 try 中导入）：{module}")
        else:
            failures.append(
                f"缺少模块 {module}（源码里是无保护导入，运行时会 ImportError）"
            )

    for path, text in analysed.items():
        if not text.startswith(REFERENCE_HEADER):
            continue
        packed_name = f"_resource_data/{path.stem}.bin"
        if packed_name not in packed:
            failures.append(f"引用模块 {path.stem} 对应的载荷 {packed_name} 没有打进包")

    return failures, warnings


def probe_tool(name, timeout=12):
    """真实启动一次工具做冒烟探测（有副作用，需显式开启）。"""
    executable = FILES_DIR / f"{name}.exe"
    if not executable.is_file():
        return FAIL, "缺少可执行文件"
    workdir = PROJECT / "_build_validation" / "prebuild-probe"
    workdir.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["PYTHONIOENCODING"] = "utf-8"
    try:
        process = subprocess.Popen(
            [str(executable)],
            cwd=str(workdir),
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            env=env,
            creationflags=CREATE_NO_WINDOW,
        )
    except OSError as exc:
        return FAIL, f"无法启动：{exc}"
    try:
        output, _ = process.communicate(timeout=timeout)
        code = process.returncode
    except subprocess.TimeoutExpired:
        process.kill()
        process.communicate()
        return OK, f"启动后持续运行 {timeout}s（已终止）"

    text = (output or b"").decode("utf-8", "replace")
    for pattern in FATAL_LAUNCH_PATTERNS:
        if pattern in text:
            return FAIL, f"启动即失败：{pattern}"
    if code == 0:
        return OK, "已启动并正常退出"
    if "EOFError" in text:
        return OK, "已进入交互阶段（标准输入为空，EOF 退出）"
    return (
        WARN,
        f"退出码 {code}，输出片段：{text.strip().splitlines()[-1][:120] if text.strip() else '无'}",
    )


