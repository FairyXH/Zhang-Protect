def _decode_console(data):
    """7z.exe 按系统 OEM 代码页输出，中文路径直接 utf-8 解会变乱码。"""
    for encoding in ("oem", "gbk", "utf-8"):
        try:
            return data.decode(encoding)
        except (LookupError, UnicodeDecodeError):
            continue
    return data.decode("utf-8", "replace")


def verify_archive(path, timeout=900):
    """用 files\\7z.exe 做 CRC 校验；失败抛 Invalid。"""
    if not SEVEN_ZIP.is_file():
        raise Invalid("缺少 files/7z.exe，无法校验压缩包")
    try:
        done = subprocess.run(
            [str(SEVEN_ZIP), "t", "-y", "-bd", str(path)],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=timeout,
            creationflags=CREATE_NO_WINDOW,
        )
    except subprocess.TimeoutExpired:
        raise Invalid(f"校验超时（>{timeout}s）")
    except OSError as exc:
        raise Invalid(f"无法启动 7z.exe：{exc}")

    if done.returncode == 0:
        return

    output = _decode_console(done.stdout or b"")
    markers = (
        "unexpected",
        "cannot open",
        "can not open",
        "can't open",
        "crc",
        "data error",
        "wrong password",
        "headers error",
        "is not archive",
        "unsupported",
    )
    found = []
    for line in output.splitlines():
        text = line.strip()
        if not text:
            continue
        lowered = text.lower()
        if any(marker in lowered for marker in markers) and text not in found:
            found.append(text)
    raise Invalid("；".join(found[:2]) or f"7z 返回码 {done.returncode}")


