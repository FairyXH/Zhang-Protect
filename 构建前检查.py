class Report:
    def __init__(self):
        self.items = []
        self.stages = []

    def add(self, group, subject, status, detail=""):
        self.items.append(
            {"group": group, "subject": subject, "status": status, "detail": detail}
        )

    def counts(self, group):
        subset = [item for item in self.items if item["group"] == group]
        return {
            status: sum(1 for item in subset if item["status"] == status)
            for status in (OK, FAIL, WARN, SKIP)
        }

    def statuses(self):
        return {
            status: sum(1 for i in self.items if i["status"] == status)
            for status in (OK, FAIL, WARN, SKIP)
        }

    def failures(self):
        return [item for item in self.items if item["status"] == FAIL]

    def warnings(self):
        return [item for item in self.items if item["status"] == WARN]


def run_stage(report, index, total, title, jobs, subjects, worker, label=str):
    """并发跑一个检查组；worker(subject) 返回 (status, detail)。"""
    started = time.perf_counter()
    results = {}
    if subjects:
        with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
            futures = {pool.submit(worker, subject): subject for subject in subjects}
            for future in concurrent.futures.as_completed(futures):
                subject = futures[future]
                try:
                    results[subject] = future.result()
                except Exception as exc:  # noqa: BLE001 - 单个对象异常不应中断整轮检查
                    results[subject] = (FAIL, f"{type(exc).__name__}: {exc}")
    elapsed = time.perf_counter() - started

    counts = {status: 0 for status in (OK, FAIL, WARN, SKIP)}
    for subject in subjects:
        status, detail = results.get(subject, (FAIL, "未返回结果"))
        counts[status] += 1
        report.add(index, label(subject), status, detail)

    total_count = len(subjects)
    header = f"[{index}/{total}] {title}"
    verdict = f"{counts[OK]}/{total_count} 通过"
    if counts[FAIL]:
        verdict += f"  {counts[FAIL]} 失败"
    if counts[WARN]:
        verdict += f"  {counts[WARN]} 警告"
    report.stages.append((header, verdict, elapsed))
    print(
        f"{header} {'.' * max(4, 62 - len(header) - len(verdict))} {verdict}  {elapsed:.1f}s"
    )
    sys.stdout.flush()


def render_details(report):
    failures = report.failures()
    warnings = report.warnings()
    if failures:
        print("-" * 78)
        print(f"失败明细（{len(failures)} 项）")
        for item in failures:
            print(f"  [{item['group']}/{4}] {item['subject']}")
            print(f"        {item['detail']}")
    if warnings:
        print("-" * 78)
        print(f"警告（{len(warnings)} 项，不阻断打包）")
        for item in warnings:
            print(f"  [{item['group']}/{4}] {item['subject']}: {item['detail']}")


