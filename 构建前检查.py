def load_payload_entries():
    """从 makefile.py 里取出 (源文件名, 模块名, 变量名) 三元组列表。"""
    if not MAKEFILE.is_file():
        raise Invalid("缺少 makefile.py")
    try:
        tree = ast.parse(MAKEFILE.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError as exc:
        raise Invalid(f"makefile.py 语法错误：{exc.msg}")

    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign) or not isinstance(node.value, ast.List):
            continue
        if not any(isinstance(t, ast.Name) and t.id == "files" for t in node.targets):
            continue
        entries = []
        for element in node.value.elts:
            if not isinstance(element, ast.Tuple) or len(element.elts) != 3:
                continue
            values = []
            for item in element.elts:
                if not isinstance(item, ast.Constant) or not isinstance(
                    item.value, str
                ):
                    break
                values.append(item.value)
            if len(values) == 3:
                entries.append(tuple(values))
        if entries:
            return entries
    raise Invalid("makefile.py 里没有找到可解析的 files 列表")


def check_payload(source_name, module_name, var_name):
    """返回问题列表；空列表表示通过。"""
    problems = []
    source = FILES_DIR / source_name
    blob = RESOURCE_DIR / f"{module_name}.bin"
    module = PROJECT / f"{module_name}.py"

    if not source.is_file():
        problems.append(f"缺少源文件 files/{source_name}")
    if not blob.is_file():
        problems.append(f"缺少载荷 _resource_data/{module_name}.bin")
    else:
        try:
            with blob.open("rb") as handle:
                magic = handle.read(len(RESOURCE_MAGIC))
            blob_size = blob.stat().st_size
            if magic != RESOURCE_MAGIC:
                problems.append("载荷缺少 ZPRES 魔数头")
            if source.is_file():
                expected = source.stat().st_size
                if blob_size - len(RESOURCE_MAGIC) != expected:
                    problems.append(
                        f"载荷大小与源文件不一致（{blob_size - len(RESOURCE_MAGIC)} != {expected}）"
                    )
        except OSError as exc:
            problems.append(f"载荷无法读取：{exc}")

    if not module.is_file():
        problems.append(f"缺少引用模块 {module_name}.py")
    else:
        text = module.read_text(encoding="utf-8", errors="replace")
        if not text.startswith(REFERENCE_HEADER):
            problems.append("引用模块不是生成格式（疑似旧版 base64 字面量未迁移）")
        elif f"{var_name} = _EmbeddedResource(" not in text:
            problems.append(f"引用模块里没有变量 {var_name}")
        try:
            ast.parse(text)
        except SyntaxError as exc:
            problems.append(f"引用模块语法错误：{exc.msg}")
    return problems


def find_orphan_payloads(entries):
    """_resource_data 里存在但 makefile.py 未登记的载荷。"""
    known = {module_name for _, module_name, _ in entries}
    if not RESOURCE_DIR.is_dir():
        return []
    return sorted(
        path.name for path in RESOURCE_DIR.glob("*.bin") if path.stem not in known
    )


