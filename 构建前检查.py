# PE 结构
# --------------------------------------------------------------------------- #
def inspect_pe(path):
    """校验 PE 结构，返回 (machine, 节区数)；不合法时抛 Invalid。"""
    try:
        size = path.stat().st_size
    except OSError as exc:
        raise Invalid(f"无法读取：{exc}")
    if size == 0:
        raise Invalid("文件为 0 字节")
    if size < 0x100:
        raise Invalid(f"文件过小（{size} 字节）")

    with path.open("rb") as handle:
        head = handle.read(0x40)
        if len(head) < 0x40:
            raise Invalid("DOS 头被截断")
        if head[:2] != b"MZ":
            raise Invalid("缺少 MZ 头")
        e_lfanew = int.from_bytes(head[0x3C:0x40], "little")
        if e_lfanew < 0x40 or e_lfanew + 24 > size:
            raise Invalid(f"PE 头偏移越界（e_lfanew={e_lfanew}，文件 {size} 字节）")

        handle.seek(e_lfanew)
        if handle.read(4) != b"PE\0\0":
            raise Invalid("缺少 PE 签名")
        coff = handle.read(20)
        if len(coff) < 20:
            raise Invalid("COFF 头被截断")
        machine, section_count, _, _, _, opt_size, _ = struct.unpack("<HHIIIHH", coff)
        if machine not in (0x014C, 0x8664):
            raise Invalid(f"未知的机器类型 0x{machine:04X}")
        if not 1 <= section_count <= 96:
            raise Invalid(f"节区数异常（{section_count}）")
        if opt_size < 0x60:
            raise Invalid(f"可选头长度异常（{opt_size}）")

        handle.seek(e_lfanew + 24)
        if handle.read(2) not in (b"\x0b\x01", b"\x0b\x02"):
            raise Invalid("可选头 magic 异常")

        table = e_lfanew + 24 + opt_size
        if table + section_count * 40 > size:
            raise Invalid("节区表越界（文件被截断）")
        handle.seek(table)
        for index in range(section_count):
            raw = handle.read(40)
            if len(raw) < 40:
                raise Invalid("节区表被截断")
            raw_size, raw_pointer = struct.unpack("<II", raw[16:24])
            if raw_size and raw_pointer + raw_size > size:
                raise Invalid(f"第 {index} 个节区的数据越界（文件被截断）")

    return machine, section_count


