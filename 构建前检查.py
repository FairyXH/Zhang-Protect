"""构建前完整性检查。

在 make.bat 打包主程序之前，校验 files\\ 里所有会被内嵌进 ZhangProtect.exe 的资源：

1. 7z 压缩包：用 files\\7z.exe 做 CRC 全量校验（与运行时同一个解压器）；
2. exe / dll：PE 结构校验，抓 0 字节、下载/拷贝中断、节区越界这类
   "双击后提示此应用无法在你的电脑上运行" 的坏文件；
3. makefile.py 产出的载荷：_resource_data\\*.bin 的魔数头、大小与源文件一致，
   引用模块格式正确且可解析；
4. make_pythontools_files.bat 打出的 PyInstaller 工具：CArchive/PYZ 可解析、
   入口脚本在包里、导入闭包里的模块一个不缺（缺哪个就点名），
   以及闭包用到的 _resource_data 载荷确实被打进了包。

检查不通过时返回码为 1，make.bat 会中止打包；全部通过后停留 5 秒再继续。

用法：
    python 构建前检查.py [--no-wait] [--run] [--jobs N] [--json 路径]

--run 会真实启动这 13 个工具做冒烟探测。这些工具多数是交互式或会改系统配置的
（restoreconfs 会还原网络、SysDispatch 会执行调度、Disable_Safety 会写防护配置），
因此默认关闭，只在需要人工确认时才加。
"""

