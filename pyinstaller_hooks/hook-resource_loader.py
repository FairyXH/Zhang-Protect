from pathlib import Path


def hook(hook_api):
    datas = []
    for node in hook_api.module_graph.iter_graph():
        filename = getattr(node, "filename", None)
        if not filename or not str(filename).endswith(".py"):
            continue
        module = Path(filename)
        try:
            with module.open("rb") as source:
                generated = source.readline(128).rstrip(b"\r\n") == (
                    b"# Generated by file2base.py; resource reference."
                )
        except OSError:
            continue
        if generated:
            resource = module.parent / "_resource_data" / (module.stem + ".bin")
            if not resource.is_file():
                raise FileNotFoundError(f"Missing resource data: {resource}")
            datas.append((str(resource), "_resource_data"))
    hook_api.add_datas(datas)
