"""Verify the frozen archive and embedded resources without running application logic."""

import ast
import hashlib
import json
from pathlib import Path
import re
import sys
import zlib

from PyInstaller.archive.readers import CArchiveReader

PROJECT = Path(__file__).resolve().parents[1]
CHUNK_SIZE = 1024 * 1024


def archive_digest(archive, entry):
    offset, compressed_size, expected_size, compressed, _ = entry
    decoder = zlib.decompressobj() if compressed else None
    digest = hashlib.sha256()
    size = 0
    with open(archive._filename, "rb") as source:
        source.seek(archive._start_offset + offset)
        remaining = compressed_size
        while remaining:
            chunk = source.read(min(remaining, CHUNK_SIZE))
            if not chunk:
                raise ValueError("Truncated archive entry")
            remaining -= len(chunk)
            if decoder is None:
                digest.update(chunk)
                size += len(chunk)
                continue
            while chunk:
                output = decoder.decompress(chunk, CHUNK_SIZE)
                digest.update(output)
                size += len(output)
                chunk = decoder.unconsumed_tail
        if decoder is not None:
            if not decoder.eof or decoder.unused_data:
                raise ValueError("Invalid compressed entry")
        if size != expected_size:
            raise ValueError(f"Entry length mismatch: {size} != {expected_size}")
    return digest.hexdigest(), size


def main():
    executable = PROJECT / "Release/ZhangProtect.exe"
    archive = CArchiveReader(str(executable))
    pyz_name = next(name for name, entry in archive.toc.items() if entry[-1] == "z")
    pyz = archive.open_embedded_archive(pyz_name)
    resources = {}
    for name, entry in archive.toc.items():
        digest, size = archive_digest(archive, entry)
        normalized = name.replace("\\", "/")
        if normalized.startswith("_resource_data/"):
            # Windows may mark DATA entries as 'b' to preserve os.X_OK semantics.
            # Byte-for-byte hashing below catches any binary rewriting by UPX.
            if entry[-1] not in ("x", "b"):
                raise ValueError(f"Unexpected resource archive entry type: {name}")
            source = PROJECT / normalized
            with source.open("rb") as stream:
                expected = hashlib.file_digest(stream, "sha256").hexdigest()
            if digest != expected:
                raise ValueError(f"Resource SHA-256 mismatch: {name}")
            resources[source.stem] = {"size": size, "sha256": digest}

    largest_reference_constant = 0
    for name in resources:
        if name not in pyz.toc:
            raise ValueError(f"Missing reference module: {name}")
        code = pyz.extract(name)
        if "EmbeddedResource" not in code.co_names:
            raise ValueError(f"Resource module is not lazy: {name}")
        for value in code.co_consts:
            if isinstance(value, (bytes, str)):
                largest_reference_constant = max(largest_reference_constant, len(value))
    if largest_reference_constant > 1024:
        raise ValueError("Unexpected large constant in resource references")

    source_tree = ast.parse((PROJECT / "main.py").read_text(encoding="utf-8"))
    for node in source_tree.body:
        if isinstance(node, ast.ImportFrom) and node.module:
            module = PROJECT / (node.module + ".py")
            if module.is_file():
                with module.open("rb") as stream:
                    marker = stream.readline(128).rstrip(b"\r\n")
                if marker == b"# Generated by file2base.py; resource reference.":
                    if node.module not in resources:
                        raise ValueError(
                            f"Imported resource was not collected: {node.module}"
                        )

    for required in (
        "resource_loader",
        "main_imports",
        "chardet",
        "tkinter",
        "scapy",
        "py7zr",
    ):
        if required not in pyz.toc:
            raise ValueError(f"Missing runtime module: {required}")
    if "main" not in archive.toc:
        raise ValueError("Missing application entry point")

    tools_script = (PROJECT / "make_pythontools_files.bat").read_text(encoding="gbk")
    auxiliary_programs = {}
    for name in re.findall(r"-n\s+(\w+)", tools_script):
        tool = PROJECT / "files" / (name + ".exe")
        embedded = CArchiveReader(str(tool))
        for entry in embedded.toc.values():
            archive_digest(embedded, entry)
        archive_name = next(
            key for key, entry in embedded.toc.items() if entry[-1] == "z"
        )
        tool_pyz = embedded.open_embedded_archive(archive_name)
        collected = {
            Path(key.replace("\\", "/")).stem
            for key in embedded.toc
            if key.replace("\\", "/").startswith("_resource_data/")
        }
        for module in resources.keys() & tool_pyz.toc.keys():
            if module not in collected:
                raise ValueError(f"Auxiliary program resource missing: {name}/{module}")
        auxiliary_programs[name] = {
            "size_bytes": tool.stat().st_size,
            "archive_entries_verified": len(embedded.toc),
            "resource_count": len(collected),
        }

    with executable.open("rb") as stream:
        exe_digest = hashlib.file_digest(stream, "sha256").hexdigest()
    report = {
        "executable": str(executable),
        "size_bytes": executable.stat().st_size,
        "sha256": exe_digest,
        "archive_entries_verified": len(archive.toc),
        "python_modules": len(pyz.toc),
        "resources_verified": len(resources),
        "resource_bytes_verified": sum(item["size"] for item in resources.values()),
        "largest_reference_constant_bytes": largest_reference_constant,
        "auxiliary_programs_verified": len(auxiliary_programs),
        "auxiliary_programs": auxiliary_programs,
        "resources": resources,
    }
    destination = PROJECT / "_build_validation/integrity-report.json"
    destination.write_text(json.dumps(report, indent=2), encoding="utf-8")
    summary = {
        key: value
        for key, value in report.items()
        if key not in ("resources", "auxiliary_programs")
    }
    print(json.dumps(summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
