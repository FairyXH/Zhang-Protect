"""Measure resource imports and copying without executing application startup."""

import importlib
import json
from pathlib import Path
import sys
import tempfile
import time
import tracemalloc

import psutil

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT))
from resource_loader import EmbeddedResource, write_resource


def main():
    modules = []
    for path in PROJECT.glob("*.py"):
        with path.open("rb") as source:
            if source.readline(128).rstrip(b"\r\n") == (
                b"# Generated by file2base.py; resource reference."
            ):
                modules.append(path.stem)
    process = psutil.Process()
    baseline = process.memory_info()
    tracemalloc.start()
    start = time.perf_counter()
    references = []
    for name in modules:
        module = importlib.import_module(name)
        references.extend(
            value
            for value in vars(module).values()
            if isinstance(value, EmbeddedResource)
        )
    import_seconds = time.perf_counter() - start
    after_import = process.memory_info()
    largest = max(
        references,
        key=lambda value: (PROJECT / "_resource_data" / value.name).stat().st_size,
    )
    with tempfile.TemporaryFile() as output:
        write_resource(output, largest)
        written = output.tell()
    _, traced_peak = tracemalloc.get_traced_memory()
    final = process.memory_info()
    print(
        json.dumps(
            {
                "resource_modules": len(modules),
                "resource_data_mib": round(
                    sum(
                        (PROJECT / "_resource_data" / value.name).stat().st_size
                        for value in references
                    )
                    / 1024**2,
                    2,
                ),
                "import_seconds": round(import_seconds, 3),
                "working_set_baseline_mib": round(baseline.rss / 1024**2, 2),
                "working_set_after_import_mib": round(after_import.rss / 1024**2, 2),
                "process_peak_working_set_mib": round(final.peak_wset / 1024**2, 2),
                "python_traced_peak_mib": round(traced_peak / 1024**2, 2),
                "largest_resource_copied_mib": round(written / 1024**2, 2),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
